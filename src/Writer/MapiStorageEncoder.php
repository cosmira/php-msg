<?php

declare(strict_types=1);

namespace Cosmira\OutlookMessage\Writer;

use Brick\Math\BigInteger;
use Cosmira\OutlookMessage\Attachment;
use Cosmira\OutlookMessage\AttachmentMethod;
use Cosmira\OutlookMessage\Mapi\Properties;
use Cosmira\OutlookMessage\Mapi\PropertyTypes;
use Cosmira\OutlookMessage\Message;
use Cosmira\OutlookMessage\Recipient;
use Cosmira\OutlookMessage\Rtf\RtfCompressor;
use Cosmira\OutlookMessage\Writer\Mapi\PropertyStreamEncoder;
use DateTimeImmutable;
use LogicException;

final class MapiStorageEncoder
{
    /**
     * Relative timestamp used for new message metadata.
     */
    private const CURRENT_TIME = 'now';

    /**
     * Canonical creation time used by this operation.
     */
    private const CREATION_TIME = 'creationTime';

    /**
     * Canonical modification time used by this operation.
     */
    private const MODIFICATION_TIME = 'lastModificationTime';

    /**
     * Canonical object type used by this operation.
     */
    private const OBJECT_TYPE = 'objectType';

    /**
     * Canonical store support mask used by this operation.
     */
    private const STORE_SUPPORT_PROPERTY = 'storeSupportMask';

    /**
     * Canonical instance key id used by this operation.
     */
    private const INSTANCE_KEY_ID = '0FF6';

    /**
     * Canonical record key id used by this operation.
     */
    private const RECORD_KEY_ID = '0FF9';

    /**
     * Windows codepage used for ANSI metadata generated by the writer.
     */
    private const CODEPAGE = 65001;

    /**
     * Message flag indicating an unmodified message.
     */
    private const MESSAGE_FLAGS_UNMODIFIED = 0x0002;

    /**
     * Message flag identifying an unsent draft.
     */
    private const MESSAGE_FLAGS_UNSENT = 0x0008;

    /**
     * Message flag indicating that attachment storages exist.
     */
    private const MESSAGE_FLAGS_HAS_ATTACH = 0x0010;

    /**
     * MAPI object-type value identifying a message.
     */
    private const OBJECT_TYPE_MESSAGE = 5;

    /**
     * Outlook icon index used for an unsent message.
     */
    private const ICON_INDEX_UNSENT_MAIL = 0x00000103;

    /**
     * Outlook icon index used for a newly created message.
     */
    private const ICON_INDEX_NEW_MAIL = 0x00000000;

    /**
     * Default MAPI importance for generated messages.
     */
    private const IMPORTANCE_NORMAL = 1;

    /**
     * Default MAPI priority for generated messages.
     */
    private const PRIORITY_NONURGENT = 0;

    /**
     * Combined storage access flags for generated message metadata.
     */
    private const ACCESS_READ_WRITE_DELETE = 7;

    /**
     * Storage access level allowing modification.
     */
    private const ACCESS_LEVEL_MODIFY = 1;

    /**
     * Store capabilities advertised by generated messages.
     */
    private const STORE_SUPPORT_MASK = 0x00050038;

    /**
     * Default Windows locale identifier for generated metadata.
     */
    private const MESSAGE_LOCALE_ID = 1033;

    /**
     * Addressing scheme used for generated sender metadata.
     */
    private const SENDER_ADDRESS_TYPE = 'SMTP';

    /**
     * MAPI object type identifying an addressable mail user.
     */
    private const RECIPIENT_OBJECT_TYPE_MAILUSER = 6;

    /**
     * MAPI display type identifying a mail user.
     */
    private const RECIPIENT_DISPLAY_TYPE_MAILUSER = 0;

    /**
     * Provider identifier used by one-off SMTP address entries.
     */
    private const ONE_OFF_ENTRY_ID_PROVIDER_UID = "\x81\x2B\x1F\xA4\xBE\xA3\x10\x19"
        ."\x9D\x6E\x00\xDD\x01\x0F\x54\x02";

    /**
     * Attachment flag indicating an inline body reference.
     */
    private const ATTACH_FLAG_RENDERED_IN_BODY = 0x04;

    /**
     * MAPI object-type value identifying an attachment.
     */
    private const OBJECT_TYPE_ATTACH = 7;

    /**
     * Encode the root MAPI streams for the given message builder.
     */
    public static function forMessage(
        MessageBuilder $builder,
        int $subStorageSize = 0,
    ): StorageStreams {
        self::bootMapi();

        $values = self::messageValues($builder);
        $streams = self::messageStreams($builder);
        $definitions = array_merge(Properties::$rootProperties, [Properties::$codepageProperty]);

        $storage = PropertyStreamEncoder::buildStorageStreams(
            $definitions,
            $values,
            $streams,
            true,
            count($builder->recipients()),
            count($builder->attachments()),
            $subStorageSize,
        );

        return PropertyStreamEncoder::appendRawProperties(
            $storage,
            $builder->rawProperties(),
            $builder->codepage,
        );
    }

    /**
     * Build fixed MAPI property values for a message.
     *
     * @return array<string, mixed>
     */
    private static function messageValues(MessageBuilder $builder): array
    {
        $timestamp = $builder->date ?? new DateTimeImmutable(self::CURRENT_TIME);
        $hasAttachments = $builder->attachments() !== [];
        $flags = self::MESSAGE_FLAGS_UNMODIFIED;
        $flags |= $builder->draft ? self::MESSAGE_FLAGS_UNSENT : 0;
        $flags |= $hasAttachments ? self::MESSAGE_FLAGS_HAS_ATTACH : 0;
        $values = [
            'access'                              => self::ACCESS_READ_WRITE_DELETE,
            'accessLevel'                         => self::ACCESS_LEVEL_MODIFY,
            'alternateRecipientAllowed'           => 1,
            self::CREATION_TIME                   => self::unixToFiletime($timestamp),
            'deleteAfterSubmit'                   => 0,
            'hasAttach'                           => $hasAttachments ? 1 : 0,
            self::MODIFICATION_TIME               => self::unixToFiletime($timestamp),
            'messageFlags'                        => $flags,
            self::OBJECT_TYPE                     => self::OBJECT_TYPE_MESSAGE,
            'readReceiptRequested'                => $builder->readReceiptRequested ? 1 : 0,
            'rtfInSync'                           => $builder->bodyRtf !== null ? 1 : 0,
            self::STORE_SUPPORT_PROPERTY          => self::STORE_SUPPORT_MASK,
            'storeUnicodeMask'                    => self::STORE_SUPPORT_MASK,
        ];

        self::addOptionalMessageValues($values, $builder);

        return $values;
    }

    /**
     * Add optional metadata that should survive a message round trip.
     *
     * @param array<string, mixed> $values
     */
    private static function addOptionalMessageValues(array &$values, MessageBuilder $builder): void
    {
        $defaults = $builder->shouldWriteMissingMetadataDefaults();

        if (self::shouldWriteOptional($builder->importance, $defaults)) {
            $values['importance'] = $builder->importance ?? self::IMPORTANCE_NORMAL;
        }

        if (self::shouldWriteOptional($builder->priority, $defaults)) {
            $values['priority'] = $builder->priority ?? self::PRIORITY_NONURGENT;
        }

        if (self::shouldWriteOptional($builder->iconIndex, $defaults)) {
            $defaultIcon = $builder->draft
                ? self::ICON_INDEX_UNSENT_MAIL : self::ICON_INDEX_NEW_MAIL;
            $values['iconIndex'] = $builder->iconIndex ?? $defaultIcon;
        }

        if (self::shouldWriteOptional($builder->messageLocaleId, $defaults)) {
            $values['messageLocaleId'] = $builder->messageLocaleId ?? self::MESSAGE_LOCALE_ID;
        }

        if (self::shouldWriteOptional($builder->codepage, $defaults)) {
            $values['codepage'] = $builder->codepage ?? self::CODEPAGE;
        }

        self::addMessageDates($values, $builder);
    }

    /**
     * Add explicit submission and delivery dates plus the preferred editor format.
     *
     * @param array<string, mixed> $values
     */
    private static function addMessageDates(array &$values, MessageBuilder $builder): void
    {
        if ($builder->date instanceof DateTimeImmutable) {
            $values['clientSubmitTime'] = self::unixToFiletime($builder->date);
        }

        if ($builder->receivedAt instanceof DateTimeImmutable) {
            $values['date'] = self::unixToFiletime($builder->receivedAt);
        }

        if ($builder->editorFormat !== null) {
            $values['messageEditorFormat'] = $builder->editorFormat;
        }
    }

    /**
     * Determine whether a metadata property should be written for this message.
     */
    private static function shouldWriteOptional(mixed $value, bool $defaults): bool
    {
        return $value !== null || $defaults;
    }

    /**
     * Build dedicated value streams for a message storage.
     *
     * @return array<string, string>
     */
    private static function messageStreams(MessageBuilder $builder): array
    {
        $streams = self::encodeBinaryProperty('300B', random_bytes(16));
        self::addSubjectStreams($streams, $builder);
        $streams += self::encodeEmptyStringProperty('0050');
        self::addSenderStreams($streams, $builder);
        self::addContentStreams($streams, $builder);
        self::addInternetStreams($streams, $builder);
        self::addDisplayRecipients($streams, '0E04', $builder->recipients(), Recipient::TYPE_TO);
        self::addDisplayRecipients($streams, '0E03', $builder->recipients(), Recipient::TYPE_CC);
        self::addDisplayRecipients($streams, '0E02', $builder->recipients(), Recipient::TYPE_BCC);

        return $streams + self::encodeStringProperty('001A', $builder->messageClass);
    }

    /**
     * Write subject and conversation-topic streams with their preserved values.
     *
     * @param array<string, string> $streams
     */
    private static function addSubjectStreams(array &$streams, MessageBuilder $builder): void
    {
        if ($builder->subject === null) {
            return;
        }

        [$prefix, $normalized] = self::splitSubject($builder->subject);
        $streams += self::encodeStringProperty('0037', $builder->subject);
        $streams += $prefix === ''
            ? self::encodeEmptyStringProperty('003D') : self::encodeStringProperty(
                '003D',
                $prefix,
            );

        $hasTopic = $builder->conversationTopic !== null
            || $builder->shouldDeriveConversationTopic();

        if ($hasTopic) {
            $streams += self::encodeStringProperty(
                '0070',
                $builder->conversationTopic ?? $normalized,
            );
        }

        $streams += self::encodeStringProperty('0E1D', $normalized);
    }

    /**
     * Write sender and representing-sender address streams.
     *
     * @param array<string, string> $streams
     */
    private static function addSenderStreams(array &$streams, MessageBuilder $builder): void
    {
        $hasNameOnly = $builder->senderName !== null && $builder->senderEmail === null;

        if ($hasNameOnly) {
            $streams += self::encodeStringPayload('0c1a', $builder->senderName);
        }

        if ($builder->senderEmail !== null) {
            $display = $builder->senderName ?? $builder->senderEmail;
            $streams += self::encodeBinaryProperty(
                '0c19',
                self::oneOffEntryId($builder->senderEmail, $display),
            );
            $shouldWriteName = $builder->senderName !== null
                || $builder->shouldWriteMissingMetadataDefaults();

            if ($shouldWriteName) {
                $streams += self::encodeStringPayload('0c1a', $display);
            }

            $streams += self::encodeStringPayload('0c1e', self::SENDER_ADDRESS_TYPE);
            $streams += self::encodeStringPayload('0c1f', $builder->senderEmail);
            $streams += self::encodeStringPayload('4022', self::SENDER_ADDRESS_TYPE);
            $streams += self::encodeStringPayload('4023', $builder->senderEmail);
            $streams += self::encodeStringPayload('4038', $display);
        }

        if ($builder->representingName !== null) {
            $streams += self::encodeStringPayload('0042', $builder->representingName);
        }

        if ($builder->representingEmail !== null) {
            $streams += self::encodeStringPayload('0064', self::SENDER_ADDRESS_TYPE);
            $streams += self::encodeStringPayload('0065', $builder->representingEmail);
        }
    }

    /**
     * Write the available plain-text, HTML, and compressed RTF bodies.
     *
     * @param array<string, string> $streams
     */
    private static function addContentStreams(array &$streams, MessageBuilder $builder): void
    {
        if ($builder->body !== null) {
            $streams += $builder->body === ''
                ? self::encodeEmptyStringProperty('1000') : self::encodeStringProperty(
                    '1000',
                    $builder->body,
                );
        }

        if ($builder->bodyHtml !== null) {
            $streams += self::encodeBinaryProperty('1013', $builder->bodyHtml);
        }

        if ($builder->bodyRtf !== null) {
            $streams += self::encodeBinaryProperty(
                '1009',
                $builder->bodyRtfCompressed ?? RtfCompressor::wrapUncompressed($builder->bodyRtf),
            );
        }
    }

    /**
     * Write Internet message identifiers and transport headers.
     *
     * @param array<string, string> $streams
     */
    private static function addInternetStreams(array &$streams, MessageBuilder $builder): void
    {
        if ($builder->headers !== null) {
            $streams += self::encodeStringProperty('007d', $builder->headers);
        }

        if ($builder->internetMessageId !== null) {
            $streams += self::encodeStringProperty('1035', $builder->internetMessageId);
        }

        if ($builder->messageSubmissionId !== null) {
            $streams += self::encodeBinaryProperty('0047', $builder->messageSubmissionId);
        }

        if ($builder->internetReferences !== null) {
            $streams += self::encodeStringProperty('1039', $builder->internetReferences);
        }

        if ($builder->inReplyToId !== null) {
            $streams += self::encodeStringProperty('1042', $builder->inReplyToId);
        }
    }

    /**
     * Encode the MAPI streams for the given recipient row.
     */
    public static function forRecipient(
        RecipientPayload $recipient,
        int $rowId = 0,
        ?int $codepage = null,
    ): StorageStreams {
        self::bootMapi();

        $streams = [];
        $values = [
            'displayType'      => self::RECIPIENT_DISPLAY_TYPE_MAILUSER,
            self::OBJECT_TYPE  => self::RECIPIENT_OBJECT_TYPE_MAILUSER,
            'rowId'            => $rowId,
            'type'             => $recipient->type,
        ];
        $displayName = $recipient->display() ?? '';
        $entryId = $recipient->email !== null
            ? self::oneOffEntryId($recipient->email, $displayName)
            : self::randomUuidUtf16();
        $streams += self::encodeBinaryProperty(self::INSTANCE_KEY_ID, random_bytes(4));
        $streams += self::encodeBinaryProperty(self::RECORD_KEY_ID, $entryId);
        $streams += self::encodeBinaryProperty('0FFF', $entryId);

        if ($recipient->name !== null) {
            $streams += self::encodeStringPayload('3001', $recipient->name);
        }

        if ($recipient->email !== null) {
            $streams += self::encodeStringPayload('3002', self::SENDER_ADDRESS_TYPE);
            $streams += self::encodeStringPayload('3003', $recipient->email);
            $streams += self::encodeBinaryProperty(
                '300B',
                self::recipientSearchKey($recipient->email),
            );
        }

        $storage = PropertyStreamEncoder::buildStorageStreams(
            Properties::$recipientProperties,
            $values,
            $streams,
            false,
        );

        return PropertyStreamEncoder::appendRawProperties(
            $storage,
            $recipient->rawProperties,
            $codepage,
        );
    }

    /**
     * Encode the editable MAPI streams for a regular or source-preserved attachment.
     */
    public static function forAttachment(
        Attachment $attachment,
        int $attachNum = 0,
        ?int $codepage = null,
    ): StorageStreams {
        self::bootMapi();

        $method = $attachment->method();
        throw_if(
            ! $method instanceof AttachmentMethod
                || $method === AttachmentMethod::EmbeddedMessage
                || ($method !== AttachmentMethod::ByValue
                    && ! AttachmentStorageMetadata::isOpaqueAttachment($attachment)),
            LogicException::class,
            'Regular attachments require the by-value attachment method '
                .'or a preserved source storage.',
        );

        $streams = [];
        $timestamp = new DateTimeImmutable(self::CURRENT_TIME);
        $recordKey = random_bytes(16);
        $renderPosition = AttachmentStorageMetadata::renderingPosition($attachment);
        $values = [
            'attachMethod'                   => $method->value,
            'attachNum'                      => $attachNum,
            self::CREATION_TIME              => self::unixToFiletime($timestamp),
            'instanceKey'                    => null,
            self::MODIFICATION_TIME          => self::unixToFiletime($timestamp),
            self::OBJECT_TYPE                => self::OBJECT_TYPE_ATTACH,
            'renderingPosition'              => $renderPosition ?? 0xFFFFFFFF,
            self::STORE_SUPPORT_PROPERTY     => self::STORE_SUPPORT_MASK,
        ];

        if ($method === AttachmentMethod::ByValue) {
            $values['attachSize'] = $attachment->size();
        }

        $streams += self::encodeBinaryProperty(self::INSTANCE_KEY_ID, random_bytes(4));
        $streams += self::encodeBinaryProperty(self::RECORD_KEY_ID, $recordKey);

        self::addAttachmentStreams($streams, $attachment);

        if ($method === AttachmentMethod::ByValue && ! $attachment->isStreamed()) {
            $streams += self::encodeBinaryProperty('3701', $attachment->data());
        }

        $isInline = $attachment->isInline();

        if ($isInline) {
            $values['attachFlags'] = self::ATTACH_FLAG_RENDERED_IN_BODY;
        }

        $storage = PropertyStreamEncoder::buildStorageStreams(
            Properties::$attachmentProperties,
            $values,
            $streams,
            false,
        );

        return PropertyStreamEncoder::appendRawProperties(
            $storage,
            $attachment->rawProperties(),
            $codepage,
        );
    }

    /**
     * Encode the MAPI streams for an embedded-message attachment.
     */
    public static function forEmbeddedAttachment(
        Attachment $attachment,
        int $attachNum = 0,
        ?int $codepage = null,
    ): StorageStreams {
        self::bootMapi();

        throw_unless(
            $attachment->message() instanceof Message,
            LogicException::class,
            'Embedded attachments require an embedded message.',
        );
        throw_unless(
            $attachment->method() === AttachmentMethod::EmbeddedMessage,
            LogicException::class,
            'Embedded attachments require the embedded-message attachment method.',
        );

        $streams = [];
        $timestamp = new DateTimeImmutable(self::CURRENT_TIME);
        $renderPosition = AttachmentStorageMetadata::renderingPosition($attachment);
        $values = [
            'attachMethod'                   => AttachmentMethod::EmbeddedMessage->value,
            'attachNum'                      => $attachNum,
            self::CREATION_TIME              => self::unixToFiletime($timestamp),
            self::MODIFICATION_TIME          => self::unixToFiletime($timestamp),
            self::OBJECT_TYPE                => self::OBJECT_TYPE_ATTACH,
            'renderingPosition'              => $renderPosition ?? 0xFFFFFFFF,
            self::STORE_SUPPORT_PROPERTY     => self::STORE_SUPPORT_MASK,
        ];
        $streams += self::encodeBinaryProperty(self::INSTANCE_KEY_ID, random_bytes(4));
        $streams += self::encodeBinaryProperty(self::RECORD_KEY_ID, random_bytes(16));

        self::addAttachmentStreams($streams, $attachment);

        $isInline = $attachment->isInline();

        if ($isInline) {
            $values['attachFlags'] = self::ATTACH_FLAG_RENDERED_IN_BODY;
        }

        $storage = PropertyStreamEncoder::buildStorageStreams(
            Properties::$attachmentProperties,
            $values,
            $streams,
            false,
        );

        $attachDataObject = pack('V', (0x3701 << 16) | 0x000D).pack('VVV', 0, 0, 0);

        return PropertyStreamEncoder::appendRawProperties(
            $storage,
            $attachment->rawProperties(),
            $codepage,
        )
            ->appendProperties($attachDataObject);
    }

    /**
     * Write attachment names, MIME metadata, and payload streams.
     *
     * @param array<string, string> $streams
     */
    private static function addAttachmentStreams(array &$streams, Attachment $attachment): void
    {
        $extension = $attachment->extension();
        $name = $attachment->name();
        $mime = $attachment->mime();
        $language = $attachment->language();
        $displayName = $attachment->displayName();
        $contentId = $attachment->contentId();

        if ($extension !== null) {
            $streams += self::encodeStringProperty('3703', $extension);
        }

        if ($name !== null) {
            $streams += self::encodeStringProperty('3704', $name);
            $streams += self::encodeStringProperty('3707', $name);
        }

        if ($mime !== null) {
            $streams += self::encodeStringProperty('370e', $mime);
        }

        if ($language !== null) {
            $streams += self::encodeStringProperty('3A0C', $language);
        }

        if ($displayName !== null) {
            $streams += self::encodeStringProperty('3001', $displayName);
        }

        if ($contentId !== null) {
            $streams += self::encodeStringProperty('3712', $contentId);
        }
    }

    /**
     * Write display strings for To, Cc, and Bcc recipients.
     *
     * @param array<string, string> $streams
     * @param RecipientPayload[]    $recipients
     */
    private static function addDisplayRecipients(
        array &$streams,
        string $propertyId,
        array $recipients,
        int $type,
    ): void {
        $display = array_values(array_map(
            static fn (RecipientPayload $recipient): string => $recipient->display() ?? '',
            array_filter(
                $recipients,
                static fn (RecipientPayload $recipient): bool => $recipient->type === $type,
            ),
        ));

        if ($display === []) {
            $streams += self::encodeEmptyStringProperty($propertyId);

            return;
        }

        $streams += self::encodeStringPayload($propertyId, implode(';', $display));
    }

    /**
     * Encode a string property with its required terminator.
     *
     * @return array<string, string>
     */
    private static function encodeStringProperty(string $id, string $value): array
    {
        return [strtolower($id) => PropertyStreamEncoder::encodeUnicodePayload($value)];
    }

    /**
     * Encode a string property without appending its terminator.
     *
     * @return array<string, string>
     */
    private static function encodeStringPayload(string $id, string $value): array
    {
        return [strtolower($id) => PropertyStreamEncoder::encodeUnicodePayload($value)];
    }

    /**
     * Encode the empty string representation required by a property type.
     *
     * @return array<string, string>
     */
    private static function encodeEmptyStringProperty(string $id): array
    {
        return [strtolower($id) => ''];
    }

    /**
     * Retain binary property strings and encode absent data as empty bytes.
     *
     * @return array<string, string>
     */
    private static function encodeBinaryProperty(string $id, string $value): array
    {
        return [strtolower($id) => $value];
    }

    /**
     * Generate a UUID encoded as UTF-16LE for MAPI metadata.
     */
    private static function randomUuidUtf16(): string
    {
        return PropertyStreamEncoder::encodeUnicodePayload(self::uuidV4());
    }

    /**
     * Generate a random UUID with RFC version and variant bits.
     */
    private static function uuidV4(): string
    {
        $bytes = random_bytes(16);
        $version = chr((ord(substr($bytes, 6, 1)) & 0x0F) | 0x40);
        $variant = chr((ord(substr($bytes, 8, 1)) & 0x3F) | 0x80);
        $bytes = substr_replace($bytes, $version, 6, 1);
        $bytes = substr_replace($bytes, $variant, 8, 1);

        return vsprintf('%s%s%s%s-%s%s-%s%s-%s%s-%s%s%s%s%s%s', str_split(bin2hex($bytes), 2));
    }

    /**
     * Encode the canonical SMTP search key for a recipient.
     */
    private static function recipientSearchKey(string $email): string
    {
        return strtoupper(self::SENDER_ADDRESS_TYPE).':'.strtoupper($email)."\0";
    }

    /**
     * Encode a one-off SMTP address entry identifier.
     */
    private static function oneOffEntryId(string $email, string $displayName): string
    {
        return pack('V', 0)
            .self::ONE_OFF_ENTRY_ID_PROVIDER_UID
            .pack('v', 0)
            .pack('v', 0x8001)
            .PropertyStreamEncoder::encodeUnicodeString($displayName)
            .PropertyStreamEncoder::encodeUnicodeString(self::SENDER_ADDRESS_TYPE)
            .PropertyStreamEncoder::encodeUnicodeString($email);
    }

    /**
     * Separate a recognized reply or forward prefix from the subject text.
     *
     * @return array{string, string}
     */
    private static function splitSubject(?string $subject): array
    {
        $isEmpty = $subject === null || $subject === '';

        if ($isEmpty) {
            return ['', ''];
        }

        $hasPrefix = preg_match(
            '/^(?P<prefix>\D{1,3}:\s)(?P<subject>.*)$/u',
            $subject,
            $matches,
        ) === 1;

        if ($hasPrefix) {
            return [$matches['prefix'], $matches['subject']];
        }

        return ['', $subject];
    }

    /**
     * Convert a Unix timestamp into little-endian Windows FILETIME bytes.
     */
    private static function unixToFiletime(DateTimeImmutable $date): BigInteger
    {
        $seconds = BigInteger::of((int) $date->format('U'));
        $microseconds = BigInteger::of((int) $date->format('u'));

        return $seconds
            ->plus(self::filetimeOffsetSeconds())
            ->multipliedBy(10_000_000)
            ->plus($microseconds->multipliedBy(10));
    }

    /**
     * Return the interval between the Windows and Unix epochs.
     */
    private static function filetimeOffsetSeconds(): BigInteger
    {
        return BigInteger::of(11644473600);
    }

    /**
     * Initialize shared property types and definitions before encoding.
     */
    private static function bootMapi(): void
    {
        Properties::init();
        PropertyTypes::init();
    }
}
